"""Export every General Drumkit section, retaining the first eight pad mappings."""
from pathlib import Path
import wave
from parse_default_template import parse_asset
from export_template_wav import pcm_for_section

root=Path(__file__).resolve().parent.parent
data=(root/'orgx/app/src/main/assets/Default.Template').read_bytes()
parsed=parse_asset(data,'assets/Default.Template')
instrument=parsed['instruments'][9]
sections={s['note']:s for s in instrument['sounds'][0]['sections']}
lines=['package com.hovait.orgx','','// Generated by analysis/export_orgx_drums.py.',
       'data class DrumRegion(val note:Int,val resource:Int,val gain:Double,val pan:Int)',
       'object ReferenceDrumPads { val entries=listOf(']
pads=[36,38,42,39,45,50,49,56]
for note in pads+sorted(set(sections)-set(pads)):
    section=sections[note]
    assert section['loop']==0 and section['tune']==0
    name=f'orgx_drum_{note}'
    with wave.open(str(root/f'orgx/app/src/main/res/raw/{name}.wav'),'wb') as out:
        out.setnchannels(section['channels']);out.setsampwidth(2)
        out.setframerate(section['sample_rate'])
        out.writeframes(pcm_for_section(data,parsed,section))
    gain=instrument['volume']*section['volume']/10000
    lines.append(f'    DrumRegion({note},R.raw.{name},{gain},{section["pan"]}),')
lines.append(')}')
(root/'orgx/app/src/main/java/com/hovait/orgx/ReferenceDrumPads.kt').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'Exported {len(sections)} General Drumkit samples')
